// Assembles README.md — ordered like a pitch: who → what → how → proof → contact.
const banner = (name) => `<!-- ========================================================= -->
<!--                ${name.padEnd(41)}-->
<!-- ========================================================= -->`;

const slide = (src, alt, href = '') => {
  const img = `<img src="${src}" width="100%" alt="${alt}"/>`;
  return `<p align="center">
  ${href ? `<a href="${href}">${img}</a>` : img}
</p>`;
};

const badge = (label, color, logo, url) =>
  `<a href="${url}"><img src="https://img.shields.io/badge/${encodeURIComponent(label)}-${color}?style=for-the-badge&logo=${logo}&logoColor=white" alt="${label}"/></a>`;

export function readme(cfg, data) {
  const u = cfg.username;
  const repoUrl = (name) => data.repos.find((r) => r.name.toLowerCase() === name.toLowerCase())?.url || `https://github.com/${u}/${name}`;
  const contacts = cfg.cta.contacts.filter((x) => x.value && x.url);
  const primary = contacts[0]?.url || `https://github.com/${u}`;

  const grid = cfg.intro.grid;
  const gridRows = [grid.slice(0, 2), grid.slice(2, 4)]
    .map((row) => `<tr>\n${row.map((g) => `<td>\n\n<strong>${g.title}</strong><br> <sub>${g.items}</sub>\n\n</td>`).join('\n')}\n</tr>`)
    .join('\n');

  const projectLinks = cfg.projects.map((p) => `<a href="${repoUrl(p.repo)}"><b>${p.repo} ↗</b></a>`).join(' &nbsp;·&nbsp; ');

  const video = cfg.video?.attachmentUrl
    ? `\n\n${cfg.video.attachmentUrl}\n\n`
    : `<a href="assets/video/showreel.mp4"><img src="assets/video/crow-realm-wide.webp" width="100%" alt="Shining Crow — real-time 3D showreel"/></a>
  <br/><sub>▶ Real-time 3D, built with Three.js · click for the full 1080p cinematic</sub>`;

  const LOGO = { EMAIL: ['gmail', 'f472b6'], GITHUB: ['github', '7c3aed'], LINKEDIN: ['linkedin', '0A66C2'], PORTFOLIO: ['googlechrome', 'f59e0b'] };
  const ctaBadges = contacts.map((ct) => {
    const [logo, color] = LOGO[ct.label] || ['link', '22d3ee'];
    return badge(ct.label === 'EMAIL' ? `Email ${ct.value}` : ct.label, color, logo, ct.url);
  }).join('\n  ');

  return `<!-- ⚠️ AUTO-GENERATED by scripts/build.mjs — edit profile.config.json instead. -->

${banner('HERO')}

${slide('assets/slides/hero.svg', `${cfg.name} — ${cfg.roles.join(' · ')}`, primary)}

<p align="center">
  ${ctaBadges}
  <img src="https://hits.sh/github.com/${u}.svg?style=for-the-badge&label=PROFILE%20VIEWS&color=7c3aed&labelColor=0b0a1a" alt="profile views"/>
</p>

${banner('INTRO')}

<table align="center" width="96%">
<tr>

<td width="56%" valign="top">

<h2>${cfg.intro.heading}</h2>

${cfg.intro.paragraphs.map((p) => `<p>\n${p}\n</p>`).join('\n\n')}

<table>
${gridRows}
</table>

<p>
  <a href="${primary}"><b>→ Let's work together</b></a>
</p>

</td>

<td width="44%" align="center">

<img src="assets/video/crow-realm.webp" width="100%" alt="Real-time 3D: an iridescent crow flying through a neon canyon"/>
<br/><sub>Real-time 3D · Three.js · rendered from code</sub>

</td>

</tr>
</table>

${banner('WHAT I BUILD')}

${slide('assets/slides/services.svg', 'What I build — AI products, web platforms, mobile apps, games & 3D')}

${banner('HOW I WORK')}

${slide('assets/slides/process.svg', 'How I work — discover, design, build, ship, scale')}

${banner('AI ENGINEERING')}

${slide('assets/slides/ai.svg', 'AI engineering — LLM applications and RAG systems')}

${banner('GAME DEVELOPMENT')}

${slide('assets/slides/game.svg', 'Game development — gameplay, graphics, multiplayer')}

${banner('SYSTEM ARCHITECTURE')}

${slide('assets/slides/architecture.svg', 'System architecture')}

${banner('SELECTED WORK')}

${slide('assets/slides/projects.svg', 'Selected work and language wall')}

<p align="center">${projectLinks}</p>

${banner('ACTIVITY')}

${slide('assets/slides/activity.svg', 'Contribution activity and current focus')}

${banner('SHOWREEL')}

<p align="center">
  ${video}
</p>

${banner('LET\'S BUILD')}

${slide('assets/slides/cta.svg', `Work with ${cfg.name}`, primary)}

<p align="center">
  ${ctaBadges}
</p>

<p align="center"><sub>⚡ Live sections refresh every 6 hours via GitHub Actions · last sync ${data.fetchedAt.slice(0, 10)}</sub></p>
`;
}
