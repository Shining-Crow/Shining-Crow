// Assembles README.md: a stack of full-width animated HUD slides.
const banner = (name) => `<!-- ========================================================= -->
<!--                ${name.padEnd(41)}-->
<!-- ========================================================= -->`;

const slide = (src, alt) => `<p align="center">
  <img src="${src}" width="100%" alt="${alt}"/>
</p>`;

export function readme(cfg, data) {
  const u = cfg.username;
  const repoUrl = (name) => data.repos.find((r) => r.name.toLowerCase() === name.toLowerCase())?.url || `https://github.com/${u}/${name}`;

  const grid = cfg.intro.grid;
  const gridRows = [grid.slice(0, 2), grid.slice(2, 4)]
    .map((row) => `<tr>\n${row.map((g) => `<td>\n\n<strong>${g.title}</strong><br> <sub>${g.items}</sub>\n\n</td>`).join('\n')}\n</tr>`)
    .join('\n');

  const projectLinks = cfg.projects.map((p) => `<a href="${repoUrl(p.repo)}"><b>${p.repo}</b></a>`).join(' &nbsp;·&nbsp; ');

  const video = cfg.video?.attachmentUrl
    ? `\n\n${cfg.video.attachmentUrl}\n\n`
    : `<a href="assets/video/showreel.mp4"><img src="assets/video/showreel.jpg" width="100%" alt="Watch the Shining Crow showreel"/></a>
  <br/><sub>▶ Click to watch the 1080p showreel</sub>`;

  const socials = cfg.socials
    .filter((s) => s.url)
    .map((s) => `<a href="${s.url}"><img src="https://img.shields.io/badge/${encodeURIComponent(s.label)}-0f2a1b?style=for-the-badge&logo=${s.logo}&logoColor=3dff86" alt="${s.label}"/></a>`)
    .join('\n  ');

  return `<!-- ⚠️ AUTO-GENERATED by scripts/build.mjs — edit profile.config.json instead. -->

${banner('PREMIUM HERO')}

${slide('assets/slides/hero.svg', `${cfg.name} — ${cfg.roles.join(' · ')}`)}

${banner('PROFILE INTRO')}

<table align="center" width="96%">
<tr>

<td width="58%" valign="top">

<h2>${cfg.intro.heading}</h2>

${cfg.intro.paragraphs.map((p) => `<p>\n${p}\n</p>`).join('\n\n')}

<br>

<table>
${gridRows}
</table>

<p>
  <img src="https://komarev.com/ghpvc/?username=${u}&style=flat-square&color=22c55e&label=PROFILE+VIEWS" alt="profile views"/>
  <a href="https://github.com/${u}?tab=followers"><img src="https://img.shields.io/github/followers/${u}?style=flat-square&logo=github&color=22c55e&labelColor=071b10" alt="followers"/></a>
</p>

</td>

<td width="42%" align="center">

<img src="assets/slides/core.svg" width="100%" alt="System core — AI · Web · Mobile · Games"/>

</td>

</tr>
</table>

${banner('TECHNOLOGY UNIVERSE')}

${slide('assets/slides/universe.svg', 'Technology universe — AI, Web, Mobile, Game Dev')}

${banner('AI ENGINEERING')}

${slide('assets/slides/ai.svg', 'AI engineering — LLM applications and RAG systems')}

${banner('GAME DEVELOPMENT')}

${slide('assets/slides/game.svg', 'Game development — gameplay, graphics, multiplayer')}

${banner('SYSTEM ARCHITECTURE')}

${slide('assets/slides/architecture.svg', 'System architecture')}

${banner('CONTRIBUTION ACTIVITY')}

${slide('assets/slides/activity.svg', 'Contribution activity and current focus')}

${banner('FEATURED PROJECTS')}

${slide('assets/slides/projects.svg', 'Featured projects and language wall')}

<p align="center">${projectLinks}</p>

${banner('SHOWREEL')}

<p align="center">
  ${video}
</p>

${banner('CONNECT')}

<p align="center">
  ${socials}
</p>

<p align="center"><sub>⚡ Slides auto-refresh every 6 hours via GitHub Actions · last sync ${data.fetchedAt.slice(0, 10)}</sub></p>
`;
}
